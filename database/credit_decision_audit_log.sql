-- 3. Index for fast applicant history lookup ──────────────────────────────────
CREATE INDEX IF NOT EXISTS idx_audit_log_email
    ON credit_decision_audit_log (applicant_email, decided_at DESC);

-- 4. Add model_version column to tamweel_results ──────────────────────────────
-- (also included in add_role_column.sql — safe to run multiple times)
ALTER TABLE tamweel_results
    ADD COLUMN IF NOT EXISTS model_version TEXT DEFAULT 'xgboost-classifier-v1';
